"""Validate a candidate puzzle before it ships to the player.

A puzzle is generated by either `puzzle_generator.generate_marqusee_puzzle`
(seeded RNG over the Marqusee template) or `pdb_importer.import_pdb_puzzle`
(real RCSB structure, helices broken with P/G). Both can produce duds:

  * The "broken" structure folds nothing like the broken-helix idea — the
    pLDDT collapses below the usable range and RMSD becomes meaningless.
  * Reverting a single breaker doesn't reduce RMSD because ESMFold's
    cooperative behaviour requires several reverts to commit to the right
    fold (HP35 had this — and we accept that one, but it's the edge case).
  * The budget is too tight to ever cross the solved threshold.

This module exposes :func:`validate_puzzle`, which runs three cheap checks
against a candidate before it's added to the catalog:

1. **Endpoint reachable.** Predict the fully-reverted sequence (== original
   intended sequence) and confirm RMSD ≤ ``expected_solved_rmsd`` and mean
   pLDDT ≥ ``plddt_floor``. This proves the puzzle is *winnable in
   principle* — if even reverting every breaker doesn't reach the target,
   no player strategy will.

2. **Gradient is usable.** From the broken starter, independently try
   reverting each breaker. Count how many *individually* reduce RMSD by at
   least ``min_descent_delta``. Require ``min_helpful_reverts`` to pass.

3. **Solvable inside the budget.** ``mutation_budget`` must be ≥ the number
   of breakers, and ``baseline_rmsd / expected_solved_rmsd`` ≥
   ``baseline_gap_factor`` (default 2.5) so the puzzle has real descent
   room and isn't trivially solved.

The endpoint test is one prediction; the gradient test is one per breaker.
For easy (4 breakers) → 5 calls, medium (6) → 7, hard (9) → 10. With the
sequence cache warm, each call is ~0.5–2s — so a validation pass is on the
order of 5–20s. Generator callers should ``loop_until_valid`` over a small
number of seeds (default 4) before giving up.

The validator does NOT solve the puzzle. It walks the cheapest path that
proves the gradient is *informative enough* for a learning player. A
human can still find the puzzle annoying; we just guarantee it isn't
broken.
"""

from dataclasses import dataclass, field
import logging
from typing import Callable

from backend.services.scoring import ca_coords_from_pdb, kabsch_rmsd
from backend.services.structure_cache import mean_plddt_from_pdb

log = logging.getLogger(__name__)


PredictFn = Callable[[str], tuple[str, float]]


@dataclass(frozen=True)
class RevertProbe:
    """Outcome of independently reverting one breaker position."""
    position: int           # 0-indexed
    from_aa: str            # what was in the broken starter
    to_aa: str              # the original residue
    rmsd: float             # RMSD of the (single-revert) prediction vs target
    plddt_mean: float | None
    delta_rmsd: float       # signed: negative means improvement
    helpful: bool           # delta_rmsd <= -min_descent_delta


@dataclass(frozen=True)
class ValidationResult:
    passes: bool
    reason: str
    baseline_rmsd: float
    baseline_plddt: float | None
    endpoint_rmsd: float | None
    endpoint_plddt: float | None
    helpful_reverts: int
    total_reverts_tried: int
    probes: list[RevertProbe] = field(default_factory=list)

    def summary(self) -> str:
        if not self.passes:
            return f"REJECT: {self.reason}"
        bp = f"{self.baseline_plddt:.2f}" if self.baseline_plddt is not None else "n/a"
        ep = f"{self.endpoint_rmsd:.2f}" if self.endpoint_rmsd is not None else "n/a"
        return (
            f"PASS: baseline {self.baseline_rmsd:.2f} A (pLDDT {bp}) "
            f"-> endpoint {ep} A | "
            f"{self.helpful_reverts}/{self.total_reverts_tried} helpful reverts"
        )


def validate_puzzle(
    *,
    starter_seq: str,
    original_seq: str,
    target_pdb: str,
    mutation_budget: int,
    expected_solved_rmsd: float,
    baseline_rmsd: float,
    predict_fn: PredictFn,
    starter_plddt: float | None = None,
    plddt_floor: float = 0.6,
    min_descent_delta: float = 0.3,
    min_helpful_reverts: int = 2,
    baseline_gap_factor: float = 2.5,
) -> ValidationResult:
    """Run the three-check validation pipeline on a candidate puzzle.

    `predict_fn` is the cache-first ESMFold wrapper. Predictions are
    accumulated in the cache regardless of validation outcome (free
    warming for future plays of the same sequence).

    Failures short-circuit — we stop at the first rejection signal so a bad
    candidate doesn't burn the full N+1 predictions.
    """
    if len(starter_seq) != len(original_seq):
        return ValidationResult(
            passes=False,
            reason=f"length mismatch: starter {len(starter_seq)} vs original {len(original_seq)}",
            baseline_rmsd=baseline_rmsd,
            baseline_plddt=starter_plddt,
            endpoint_rmsd=None,
            endpoint_plddt=None,
            helpful_reverts=0,
            total_reverts_tried=0,
        )

    breaker_positions = [i for i in range(len(starter_seq)) if starter_seq[i] != original_seq[i]]
    n_breakers = len(breaker_positions)

    if n_breakers == 0:
        return ValidationResult(
            passes=False,
            reason="no breakers in starter (starter == original)",
            baseline_rmsd=baseline_rmsd,
            baseline_plddt=starter_plddt,
            endpoint_rmsd=None,
            endpoint_plddt=None,
            helpful_reverts=0,
            total_reverts_tried=0,
        )

    # ---- Check 1: budget vs breakers ----
    if mutation_budget < n_breakers:
        return ValidationResult(
            passes=False,
            reason=f"budget too tight: {mutation_budget} mutations < {n_breakers} breakers",
            baseline_rmsd=baseline_rmsd,
            baseline_plddt=starter_plddt,
            endpoint_rmsd=None,
            endpoint_plddt=None,
            helpful_reverts=0,
            total_reverts_tried=0,
        )

    # ---- Check 2: baseline gap (puzzle has room to descend) ----
    if baseline_rmsd <= 0:
        return ValidationResult(
            passes=False,
            reason=f"baseline RMSD {baseline_rmsd} ≤ 0 — caller must compute it first",
            baseline_rmsd=baseline_rmsd,
            baseline_plddt=starter_plddt,
            endpoint_rmsd=None,
            endpoint_plddt=None,
            helpful_reverts=0,
            total_reverts_tried=0,
        )
    if baseline_rmsd / max(expected_solved_rmsd, 0.1) < baseline_gap_factor:
        return ValidationResult(
            passes=False,
            reason=(
                f"baseline {baseline_rmsd:.2f} Å too close to target "
                f"{expected_solved_rmsd:.2f} Å (need ≥ {baseline_gap_factor}× gap)"
            ),
            baseline_rmsd=baseline_rmsd,
            baseline_plddt=starter_plddt,
            endpoint_rmsd=None,
            endpoint_plddt=None,
            helpful_reverts=0,
            total_reverts_tried=0,
        )

    target_ca = ca_coords_from_pdb(target_pdb)

    # ---- Check 3: endpoint reachable ----
    endpoint_pdb, _ = predict_fn(original_seq)
    endpoint_ca = ca_coords_from_pdb(endpoint_pdb)
    endpoint_rmsd = float(kabsch_rmsd(endpoint_ca, target_ca))
    endpoint_plddt = mean_plddt_from_pdb(endpoint_pdb)

    if endpoint_rmsd > expected_solved_rmsd:
        return ValidationResult(
            passes=False,
            reason=(
                f"endpoint not winnable: fully-reverted RMSD {endpoint_rmsd:.2f} Å "
                f"> threshold {expected_solved_rmsd:.2f} Å"
            ),
            baseline_rmsd=baseline_rmsd,
            baseline_plddt=starter_plddt,
            endpoint_rmsd=endpoint_rmsd,
            endpoint_plddt=endpoint_plddt,
            helpful_reverts=0,
            total_reverts_tried=0,
        )
    if endpoint_plddt is not None and endpoint_plddt < plddt_floor:
        return ValidationResult(
            passes=False,
            reason=(
                f"endpoint low confidence: pLDDT {endpoint_plddt:.2f} < {plddt_floor:.2f} "
                f"(ESMFold isn't sure about the target fold)"
            ),
            baseline_rmsd=baseline_rmsd,
            baseline_plddt=starter_plddt,
            endpoint_rmsd=endpoint_rmsd,
            endpoint_plddt=endpoint_plddt,
            helpful_reverts=0,
            total_reverts_tried=0,
        )

    # ---- Check 4: gradient — independent single-reverts ----
    probes: list[RevertProbe] = []
    helpful = 0
    for pos in breaker_positions:
        candidate = starter_seq[:pos] + original_seq[pos] + starter_seq[pos + 1:]
        pdb, _ = predict_fn(candidate)
        rmsd = float(kabsch_rmsd(ca_coords_from_pdb(pdb), target_ca))
        plddt = mean_plddt_from_pdb(pdb)
        delta = rmsd - baseline_rmsd
        is_helpful = delta <= -min_descent_delta
        if is_helpful:
            helpful += 1
        probes.append(RevertProbe(
            position=pos,
            from_aa=starter_seq[pos],
            to_aa=original_seq[pos],
            rmsd=rmsd,
            plddt_mean=plddt,
            delta_rmsd=delta,
            helpful=is_helpful,
        ))
        # Early exit: once we've collected enough helpful reverts, stop spending.
        if helpful >= min_helpful_reverts:
            break

    if helpful < min_helpful_reverts:
        return ValidationResult(
            passes=False,
            reason=(
                f"flat gradient: only {helpful}/{len(probes)} single-residue reverts "
                f"dropped RMSD by ≥ {min_descent_delta:.2f} Å "
                f"(need {min_helpful_reverts} for a learnable puzzle)"
            ),
            baseline_rmsd=baseline_rmsd,
            baseline_plddt=starter_plddt,
            endpoint_rmsd=endpoint_rmsd,
            endpoint_plddt=endpoint_plddt,
            helpful_reverts=helpful,
            total_reverts_tried=len(probes),
            probes=probes,
        )

    return ValidationResult(
        passes=True,
        reason="ok",
        baseline_rmsd=baseline_rmsd,
        baseline_plddt=starter_plddt,
        endpoint_rmsd=endpoint_rmsd,
        endpoint_plddt=endpoint_plddt,
        helpful_reverts=helpful,
        total_reverts_tried=len(probes),
        probes=probes,
    )
